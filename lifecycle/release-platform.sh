  read -r ACT BRANCH STAGE <<< "$ENTRY"
  case "$ACT" in
    pin) pin_installation "$BRANCH" ;;
    *) say "release: $BRANCH is stage $STAGE and channel $CHANNEL admits only: $ADMITS - left as it stands" ;;
  esac
done
[ "${#TARGETS[@]}" -gt 0 ] \
  || say "release: origin carries no installation yet, so nothing is pinned. A first machine names $TAG as PLATFORM_REF in its config and cuts its branch from it"
# THE CONFIGS OF THIS CHECKOUT NAME THE RELEASE A FIRST MACHINE IS CUT FROM. Every
# lifecycle/config.*.env beside the tree this runs in, the example excepted, has its
# PLATFORM_REF rewritten in place — the file keeps its identity and with it the
# owner-only rights the launcher demands.
WRITTEN=0
for CONFIG in "$CONFIG_DIR"/config.*.env; do
  [ -f "$CONFIG" ] || continue
  case "$(basename "$CONFIG")" in config.example.env) continue ;; esac
  write_config_value "$CONFIG" PLATFORM_REF "$TAG"
  WRITTEN=$((WRITTEN + 1))
done
if [ "$WRITTEN" = '0' ]; then
  say "release: no config beside this tree names a PLATFORM_REF, so none was written"
else
  say "release: PLATFORM_REF=$TAG written into $WRITTEN config(s) under lifecycle/"
fi
# THE PIN RECORDS THE STATE; THE REGENERATION CARRIES IT. Every source of every
# Application reads the install branch, so an installation stands on the release
# only once deploy-branch has merged the tag into its branch — which
# regenerate-install-branch beside this file performs on the machine, with the
# installation's config. Where that config stands beside this tree, the release
# performs it; where it does not, the release says which script does and stops
# short of it.
for FQDN_PINNED in "${PINNED[@]}"; do
  CONFIG="$CONFIG_DIR/config.${FQDN_PINNED%%.*}.env"
  if [ -f "$CONFIG" ]; then
    say "release: regenerating $FQDN_PINNED with $(basename "$CONFIG") - the release is a deploy of this installation"
    bash "$(dirname "$0")/regenerate-install-branch.sh" "$FQDN_PINNED" "$CONFIG" \
      || die "$FQDN_PINNED could not be regenerated onto $TAG; its pin stands, its branch does not carry the release yet, and every installation after it in the list was not touched" 70
  else
    say "release: no config for $FQDN_PINNED beside this tree (lifecycle/config.${FQDN_PINNED%%.*}.env), so it is pinned and not regenerated. Bring it onto $TAG with:"
    say "release:     bash lifecycle/regenerate-install-branch.sh $FQDN_PINNED <config>"
  fi
done
