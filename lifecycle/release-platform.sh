#!/usr/bin/env bash
# =============================================================================
# release-platform.sh — cut a release of the platform tree, and put every
# installation the channel admits on it, or the one that is named.
# =============================================================================
#
# USAGE (run from anywhere inside a hostyour-cloud checkout)
#   bash lifecycle/release-platform.sh <x.y.z> <stable|beta|alpha> [fqdn]
#
# THE INPUTS, AND THE THIRD IS OPTIONAL
#   version  — x.y.z, the third position three digits (0.8.305, 0.3.000). EVERY RELEASE IS A PATCH BUMP: the first
#              two numbers say what the product is and are the owner's to move.
#   channel  — the maturity CEILING of the release: alpha may reach a dev
#              installation only, beta dev and test, stable any. The channel is
#              part of the release tag; the installation is not.
#   fqdn     — ONE installation to put the release on, and no other. It is the
#              domain of the cluster, the name of its install branch, and the name
#              of its map under clusters/active. One release, one tree, any number
#              of installations: run this again with another fqdn and the tag is
#              REUSED rather than cut a second time.
#
# LEFT OFF, EVERY INSTALLATION ORIGIN CARRIES TAKES THE RELEASE. An installation
# is a branch carrying its own map under clusters/active; each is measured against
# the ceiling by its map's stage line, pinned where the channel admits it, and left
# as it stands — and said so — where it does not. Then the release finishes its own
# repository: every lifecycle/config.*.env beside the tree (the example excepted)
# has PLATFORM_REF rewritten to the tag, in place, and every pinned installation
# whose config stands there is regenerated by regenerate-install-branch beside this
# file — deploy-branch on the machine merges the tag into the branch, which is what
# carries the release; a pin only records it. An installation without a config here
# is pinned and named with the script that carries it. A FIRST machine has no branch
# yet, because the branch is cut by the deploy-branch program the installation itself
# runs, and that program fetches PLATFORM_REF as a TAG, so a commit will not do: the
# tag minted here is what its config names, and once its branch exists the same
# version and channel REUSE this tag, so the machine and every later pin stand on
# one tree. A RELEASE IS THEREFORE A DEPLOY of every installation whose config stands
# beside the tree, and the person cutting it says so when asking for it.
#
# WHAT A PLATFORM RELEASE IS, AND WHAT IT IS NOT. This repository builds no
# image, no archive and no package. THE TREE AT THE TAG IS THE RELEASE, and this
# script starts no pipeline and needs no gh and no token. It waits on the two
# things a machine needs before a pin. First, that the tag is on the REMOTE,
# because a pin naming a tag the machine cannot fetch is a pin that fails three
# systems away, in a message about a git ref rather than about a release. Second,
# that the owner's mirror serves every image the tree at the tag pulls from it.
# The tag starts the publish run of the platform tree on the owner's master, and
# that run copies those images from ghcr.io into the mirror; a pin before the copy
# is a pod that cannot pull. So the release reads each image back from the mirror,
# by its digest and without a login, with curl, and the list of them is made by the
# tree's own scripts/list-mirror-images.sh, which renders the tree with helm and yq.
# The owner's master needs a third: its recovery folder on the storage box, which a
# cold start of that machine reads instead of its own registry. The same run writes it
# after the copy, and the release lists it through a short pod it starts on that machine,
# through the operator door of its config beside the tree, before it pins that machine,
# and never another.
#
# WHY THE PIN IS WRITTEN HERE. The line `release: <tag>` in
# clusters/active/<fqdn>.yaml is what says which state an installation stands on,
# and the write belongs where the credential already is: this workstation is
# logged in to this repository, which is both the tree being released and the
# tree carrying the pin. Nothing new has to be created, held or rotated.
#
# NOTHING IS CREATED BEFORE THE TARGET IS KNOWN GOOD. The install branch is
# cloned, its map read and the ceiling checked BEFORE a tag is minted, so a
# mistyped domain or a channel that may not reach that stage costs nothing and
# leaves no tag behind naming a release nobody meant to cut.
#
# WHAT THIS DOES NOT DO. It does not stamp anything, and it touches no file under
# clusters/argocd or clusters/bootstrap. The root-app.yaml beside clusters/argocd
# carries one installation's own domain where this tree carries a placeholder, and
# writing it is the branch programs' act in the programs repository — re-run by
# deploy-branch, which regenerate-install-branch.sh beside this file performs on
# the machine, and which is the act a person performs after this one. A second
# implementation of that stamping beside them would disagree with them the first
# time either was corrected. The rest of clusters/argocd is a chart the reconciler
# renders from the cluster map, and clusters/bootstrap is seven templates the
# branch programs render onto the install branch, so neither carries a marker this
# act could put anything into.
#
# THE ORDER IS PIN, THEN REGENERATE, and they are two acts on purpose. Between
# them somebody can read what the pin now says and stop. This one ends by naming
# the second, which reads the ref off the pin this one writes rather than being
# told it a second time.
#
# THE TAG GOES ON origin/master AND NEVER ON THE LOCAL BRANCH. What is released
# is what the remote publishes; a local master may carry commits nobody else has,
# and a tag on one of those names a tree no installation could ever fetch. And the
# push gate lets through only the commit that is checked out, so the checkout is
# brought onto origin/master before anything is cut: a master that only lags -
# every unit's release pins master behind it - is fast-forwarded, and one that
# carries commits of its own, or another branch checked out, stops the run before
# a tag exists.
# =============================================================================

set -uo pipefail

die() { printf 'release: %s\n' "$1" >&2; exit "${2:-65}"; }
say() { printf '%s\n' "$1"; }

# THE VALUE OF ONE TOP-LEVEL KEY, read the way the programs checkout's own step writes
# it: a line beginning at column one with the key and a colon. A key of the same
# name indented under `global:` is a different key and is deliberately not seen.
# Surrounding quotes are the notation's and are taken off.
value_in_file() {
  local file="$1" key="$2" line value
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      "$key":*)
        value="${line#"$key":}"
        value="${value#"${value%%[![:space:]]*}"}"
        value="${value%"${value##*[![:space:]]}"}"
        case "$value" in
          \"*\") value="${value#\"}"; value="${value%\"}" ;;
          \'*\') value="${value#\'}"; value="${value%\'}" ;;
        esac
        printf '%s\n' "$value"
        return 0
        ;;
    esac
  done < "$file"
  return 1
}

# THE LINE IS REPLACED WHERE IT STANDS AND APPENDED ONLY WHERE THE FILE HAS NONE,
# which is the grammar the programs checkout's writing step uses. Appending regardless
# would leave two lines for one key, and whatever reads them takes one.
write_value_in_file() {
  local file="$1" key="$2" value="$3" line i found=0
  local -a lines=()
  while IFS= read -r line || [ -n "$line" ]; do lines+=("$line"); done < "$file"
  for ((i = 0; i < ${#lines[@]}; i++)); do
    case "${lines[$i]}" in
      "$key":*) lines[$i]="$key: $value"; found=1; break ;;
    esac
  done
  [ "$found" = '1' ] || lines+=("$key: $value")
  : > "$file"
  for line in "${lines[@]}"; do printf '%s\n' "$line" >> "$file"; done
}

value_in_text() { # key, on stdin -> the value of the top-level line, unquoted
  local key="$1" line value
  while IFS= read -r line; do
    case "$line" in
      "$key":*)
        value="${line#"$key":}"
        value="${value#"${value%%[![:space:]]*}"}"
        case "$value" in
          \"*\") value="${value#\"}"; value="${value%\"}" ;;
          \'*\') value="${value#\'}"; value="${value%\'}" ;;
        esac
        printf '%s\n' "$value"
        return 0
        ;;
    esac
  done
  return 1
}
write_config_value() { # file, KEY, value -> KEY='value' rewritten in place, appended when absent
  local file="$1" key="$2" value="$3" line i found=0
  local -a lines=()
  while IFS= read -r line || [ -n "$line" ]; do lines+=("$line"); done < "$file"
  for ((i = 0; i < ${#lines[@]}; i++)); do
    case "${lines[$i]}" in
      "$key="*) lines[$i]="$key='$value'"; found=1; break ;;
    esac
  done
  [ "$found" = '1' ] || lines+=("$key='$value'")
  : > "$file"
  for line in "${lines[@]}"; do printf '%s\n' "$line" >> "$file"; done
}
config_value() { # file, KEY -> the value of its last KEY='value' line, the one the shell sourcing the file keeps
  sed -n "s/^$2='\([^']*\)'.*\$/\1/p" "$1" | tail -n 1
}
VERSION="${1:-}"
CHANNEL="${2:-}"
FQDN="${3:-}"

[ -n "$VERSION" ] && [ -n "$CHANNEL" ] \
  || die 'usage: lifecycle/release-platform.sh <x.y.z> <stable|beta|alpha> [fqdn]' 64
[[ "$VERSION" =~ ^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.([0-9]{3}|0|[1-9][0-9]*)$ ]] \
  || die "version must be x.y.z, the third position three digits such as 000 (got '$VERSION')" 64
case "$CHANNEL" in
  alpha) ADMITS='dev' ;;
  beta) ADMITS='dev test' ;;
  stable) ADMITS='dev test prod' ;;
  *) die "channel must be stable, beta or alpha (got '$CHANNEL')" 64 ;;
esac

command -v git >/dev/null 2>&1 \
  || die 'git is not on this path, and a platform release is cut, pushed and pinned with it'
for TOOL in curl helm yq jq tar; do
  command -v "$TOOL" >/dev/null 2>&1 \
    || die "$TOOL is not on this path, and the release lists the images, tools and charts of its tag and reads them back from the mirror with it"
done
# THE LONGEST WAIT FOR THE MIRROR, in seconds. The publish run of the tag waits in
# the release queue behind at most two runs, each held to an hour, and then copies.
MIRROR_WAIT="${RELEASE_MIRROR_WAIT:-7200}"
[[ "$MIRROR_WAIT" =~ ^[0-9]+$ ]] \
  || die "RELEASE_MIRROR_WAIT is the number of seconds the release waits for the mirror at most (got '$MIRROR_WAIT')" 64
git rev-parse --is-inside-work-tree >/dev/null 2>&1 \
  || die 'not inside a git repository. Run this from a checkout of the platform tree' 66

# THE REMOTE VIEW FIRST, for two reasons. Mint-once has to see the tags somebody
# else pushed, or a second workstation mints a second tag for the same version
# and channel instead of reusing the one that exists. And the tag below is put on
# origin/master, which a checkout that has not fetched resolves to whatever it
# last saw.
git fetch --quiet --tags origin \
  || die 'origin could not be fetched, so neither the tag nor the pin would be about what the remote carries' 69
git rev-parse --verify --quiet origin/master >/dev/null \
  || die 'origin carries no master, and master is what a platform release is cut from' 69
if [ "$(git rev-parse --verify HEAD)" != "$(git rev-parse --verify origin/master)" ]; then
  if [ "$(git symbolic-ref --quiet --short HEAD)" != master ] || ! git merge-base --is-ancestor HEAD origin/master; then
    die 'this checkout is not master, or carries commits origin/master does not, so it cannot be brought onto origin/master: the tag goes there and the push gate lets through only what is checked out. Check out master and push or drop its own commits, then release again'
  fi
  git merge --quiet --ff-only origin/master \
    || die 'master lags origin/master and could not be fast-forwarded onto it - the lines above say why. The tag goes on origin/master and the push gate lets through only what is checked out'
  say 'release: master is fast-forwarded onto origin/master, where the tag goes - the push gate lets through only what is checked out'
fi

# EVERYTHING THAT NEEDS AN INSTALLATION STANDS IN THE BLOCK BELOW, and a run that
# names none skips it. What is skipped is the clone, the map, the channel ceiling
# and, at the end of this file, the pin. The mint is not: a tag that names no
# installation is exactly what a first machine is given.
if [ -n "$FQDN" ]; then
  # THE TREE IS CLONED FRESH FOR THE WRITE. The pin stands on an install branch,
  # and checking one out in the tree somebody is standing in is a thing a release
  # has no business doing.
  URL="$(git remote get-url origin)"
  [ -n "$URL" ] || die 'this checkout has no origin to clone, so there is no branch to pin' 69
  WORK="$(mktemp -d)"
  trap 'rm -rf "$WORK"' EXIT
  git clone --quiet --single-branch --branch "$FQDN" "$URL" "$WORK" \
    || die "origin has no branch $FQDN. An installation is pinned on its own install branch, and there is none of that name" 66

  MAP="clusters/active/${FQDN}.yaml"
  [ -f "$WORK/$MAP" ] \
    || die "branch $FQDN carries no $MAP. That map is where an installation records what it is, and the pin is one line in it" 66

  # THE CEILING IS ENFORCED HERE, and this is the only place that can. The manager's
  # release client only warns because a pipeline refuses afterwards; a platform
  # release has no pipeline, so a refusal that did not happen here would not happen
  # at all, and a prod installation would stand on an alpha tree.
  STAGE="$(value_in_file "$WORK/$MAP" stage)"
  [ -n "$STAGE" ] \
    || die "$MAP on branch $FQDN states no stage, so the channel ceiling cannot be checked, and a check that cannot measure must not report a pass" 65
  case " $ADMITS " in
    *" $STAGE "*) ;;
    *) die "$FQDN is stage $STAGE and channel $CHANNEL admits only: $ADMITS. Nothing else would refuse this, so this does." 65 ;;
  esac
fi

# THE STAGE IS NOT A DOMAIN LABEL, and this is the one place that can still say so
# before a tree reaches a machine. An API group is a reverse domain name fixed by
# whoever wrote the software - triggers.tekton.dev, cert-manager.io, argoproj.io -
# and no part of it varies with an installation's stage. Written as the stage
# placeholder it renders correctly on a dev installation by accident, because the
# stamp puts "dev" back, and names a group no cluster registers on every other
# stage. On such a stage the cicd project permits triggers.tekton.<stage>, ArgoCD
# cannot manage the ClusterInterceptors, and the tekton application stands
# OutOfSync for ever with the image-builder behind it.
#
# READ OFF origin/master, not the working tree: that is the tree this release
# publishes, and a correction sitting uncommitted beside it would let a release
# claim a fix nobody can fetch.
PLACED=$(git grep -nE '^[[:space:]]*(-[[:space:]]+)?(group|apiVersion):[[:space:]]*[^[:space:]]*__STAGE__' \
  origin/master -- clusters/argocd 2>/dev/null | sed 's/$/;/' | tr -d '\n')
[ -z "$PLACED" ] \
  || die "a stage placeholder stands where an API group or an apiVersion belongs, and neither ever varies with a stage: $PLACED correct it on master and release again" 65

# MINT-ONCE: exactly one release tag per version and channel. A later run for the
# same pair reuses it, which is how one release reaches a further installation
# without a second tree ever being cut.
PREFIX="${VERSION}-${CHANNEL}-"
EXISTING="$(git tag -l "${PREFIX}*" | sort | tail -1)"

# A TAG THAT NEVER REACHED ORIGIN AND NAMES ANOTHER COMMIT IS RESIDUE, and reusing
# it aims every retry at the commit a refused push left behind. The tag is minted
# before it is pushed, so a push the pre-push hook refuses leaves it standing here
# and nowhere else; the next run finds it, reuses it, and is refused again — for
# the same reason, printed as if it were about the new attempt, until somebody
# deletes the tag by hand.
#
# A TAG THAT IS ON ORIGIN IS LEFT EXACTLY AS IT STANDS, whatever commit it names.
# That is mint-once itself: one release per version and channel, reused so a
# release already cut reaches a second installation without a second tree.
if [ -n "$EXISTING" ] \
  && ! git ls-remote --exit-code --tags origin "refs/tags/${EXISTING}" >/dev/null 2>&1 \
  && [ "$(git rev-parse --verify --quiet "${EXISTING}^{commit}")" != "$(git rev-parse --verify origin/master)" ]; then
  say "release: $EXISTING stands on this workstation only and names $(git rev-parse --short=7 "${EXISTING}^{commit}"), not the commit this release is cut from. A run whose push was refused left it behind; it is dropped and cut again."
  git tag -d "$EXISTING" >/dev/null \
    || die "the leftover tag $EXISTING could not be dropped, and reusing it would put this release on a commit nobody is releasing" 69
  EXISTING=""
fi

if [ -n "$EXISTING" ]; then
  TAG="$EXISTING"
  if [ -n "$FQDN" ]; then
    say "release: reusing $TAG. One release per version and channel, so putting it on $FQDN cuts nothing new"
  else
    say "release: reusing $TAG. One release per version and channel, so this run cuts nothing new"
  fi
else
  TS14="$(date -u +%Y%m%d%H%M%S)"
  TAG="${VERSION}-${CHANNEL}-${TS14}"
  git tag -a "$TAG" -m 'the platform, cut as a release' origin/master \
    || die "the tag $TAG could not be put on origin/master"
  SHA7="$(git rev-parse --short=7 "${TAG}^{commit}")"
  say "release: minted $TAG on origin/master (commit $SHA7)"
fi

if git rev-parse --verify --quiet master >/dev/null; then
  AHEAD="$(git rev-list --count origin/master..master)"
  [ "$AHEAD" = '0' ] \
    || say "release: your local master is $AHEAD commits ahead of origin/master, and those commits are not in this release"
fi

# NOTHING IS PINNED BEFORE IT EXISTS. The push is what makes the tag fetchable;
# the read-back is what proves it, and it is asked of the REMOTE rather than of
# this checkout, which already has the tag whatever the remote thinks.
git push --quiet origin "refs/tags/$TAG" \
  || die "the tag $TAG could not be pushed to origin, so it exists on this machine only and nothing was pinned" 74
[ -n "$(git ls-remote --tags origin "refs/tags/$TAG")" ] \
  || die "origin does not carry $TAG after the push, so a machine could not fetch it and nothing was pinned" 74
say 'release: the tag stands on the remote, so a machine that fetches origin can resolve it'

# NOTHING IS PINNED BEFORE THE MIRROR SERVES THE IMAGES OF THE TAG. The list is the
# one the publish run of the tag copies: the tree at the tag prints it, so a list
# of this checkout could name other images than the run copied. Each entry is
# `<source> <mirror name>`, the mirror name `<registry>/<owner>/ghcr.io/<path>:<tag>@<digest>`;
# it is served when a GET of its manifest by that digest, without a login as every
# cluster pulls, answers 200 and names the same digest. The release reads every
# entry again every 30 seconds until all are served, and stops once MIRROR_WAIT
# has passed with one still missing: by name, before any pin, any config and any
# regeneration. A later run reuses the tag and reads again.
LISTED="$(mktemp -d)" && mkdir "$LISTED/tree" \
  || die 'no temporary directory could be made for the tree at the tag, and nothing was pinned' 69
trap 'rm -rf "${WORK:-}" "$LISTED"' EXIT
git archive --format=tar "$TAG" | tar -x -C "$LISTED/tree" \
  || die "the tree at $TAG could not be unpacked to list its images, and nothing was pinned"
[ -f "$LISTED/tree/scripts/list-mirror-images.sh" ] \
  || die "the tree at $TAG carries no scripts/list-mirror-images.sh, so nothing names the images its clusters pull from the mirror, and nothing was pinned"
bash "$LISTED/tree/scripts/list-mirror-images.sh" > "$LISTED/mirror.list" \
  || die "the images of $TAG could not be listed - the lines above say why - and nothing was pinned"
mirror_unserved() { # the list -> each mirror name in it that the mirror does not serve at its digest, one per line
  local target name digest code served
  while read -r _ target; do
    name="${target%@*}"
    digest="${target##*@}"
    name="${name%:*}"
    : > "$LISTED/headers"
    code="$(curl -sS --connect-timeout 10 --max-time 60 -o /dev/null -D "$LISTED/headers" -w '%{http_code}' \
      -H 'Accept: application/vnd.oci.image.index.v1+json, application/vnd.oci.image.manifest.v1+json, application/vnd.docker.distribution.manifest.list.v2+json, application/vnd.docker.distribution.manifest.v2+json' \
      "https://${name%%/*}/v2/${name#*/}/manifests/${digest}" 2>/dev/null)" || code=000
    served="$(tr -d '\r' < "$LISTED/headers" | awk 'tolower($1) == "docker-content-digest:" { print $2 }' | tail -n 1)"
    [ "$code" = 200 ] && [ "$served" = "$digest" ] || printf '%s\n' "$target"
  done < "$1"
}
LISTED_COUNT="$(grep -c . "$LISTED/mirror.list")"
MIRROR_DEADLINE=$((SECONDS + MIRROR_WAIT))
while :; do
  UNSERVED="$(mirror_unserved "$LISTED/mirror.list")"
  [ -z "$UNSERVED" ] && break
  [ "$SECONDS" -lt "$MIRROR_DEADLINE" ] \
    || die "the mirror does not serve $(printf '%s\n' "$UNSERVED" | grep -c .) of the $LISTED_COUNT images of $TAG after ${MIRROR_WAIT}s: $(printf '%s\n' "$UNSERVED" | sed 's/$/;/' | tr '\n' ' ')the publish run of $TAG on the owner's master copies them. Nothing was pinned. Read that run, then release again: the tag is reused" 69
  sleep 30
done
say "release: the mirror serves all $LISTED_COUNT images of $TAG at their digests, read without a login"

# THE TOOLS AND CHARTS ARE HELD THE SAME WAY, by the same tree at the tag: scripts/list-mirror-sources.sh
# prints one line per row of its mirror-sources.table, the list the publish run of the tag copies, and
# mirror_source_held of the tree's own files/mirror-sources.sh reads a row exactly as the mirror task does,
# by the anonymous GET of the manifest under the row's tag, which must answer 200 and name one layer whose
# digest is the row's sha256. The wait is the one the images already spent: a row is read again every 30
# seconds until MIRROR_WAIT has passed, and the release stops naming each row the mirror does not serve.
SOURCES_LIB='clusters/inventories/consumer-build/files/mirror-sources.sh'
for FILE in scripts/list-mirror-sources.sh "$SOURCES_LIB"; do
  [ -f "$LISTED/tree/$FILE" ] \
    || die "the tree at $TAG carries no $FILE, so nothing names the tools and charts its clusters read from the mirror, and nothing was pinned"
done
bash "$LISTED/tree/scripts/list-mirror-sources.sh" > "$LISTED/sources.list" \
  || die "the tools and charts of $TAG could not be listed - the lines above say why - and nothing was pinned"
# shellcheck disable=SC1090
. "$LISTED/tree/$SOURCES_LIB"
sources_unserved() { # the list -> each row of it that the mirror does not serve, one per line: its owned reference and what the mirror answered
  local line parts held
  while read -r line; do
    read -r -a parts <<< "$line"
    held="$(mirror_source_held "${parts[${#parts[@]} - 2]}" "${parts[${#parts[@]} - 3]}" "$LISTED/held")"
    case "$held" in
      served\ *) ;;
      *) printf '%s (%s)\n' "${parts[${#parts[@]} - 2]}" "$held" ;;
    esac
  done < "$1"
}
SOURCES_COUNT="$(grep -c . "$LISTED/sources.list")"
while :; do
  UNSERVED="$(sources_unserved "$LISTED/sources.list")"
  [ -z "$UNSERVED" ] && break
  [ "$SECONDS" -lt "$MIRROR_DEADLINE" ] \
    || die "the mirror does not serve $(printf '%s\n' "$UNSERVED" | grep -c .) of the $SOURCES_COUNT tools and charts of $TAG after ${MIRROR_WAIT}s: $(printf '%s\n' "$UNSERVED" | sed 's/$/;/' | tr '\n' ' ')the publish run of $TAG on the owner's master copies them. Nothing was pinned. Read that run, then release again: the tag is reused" 69
  sleep 30
done
say "release: the mirror serves all $SOURCES_COUNT tools and charts of $TAG"

# EVERY INSTALLATION ORIGIN CARRIES TAKES THE RELEASE, or the one that was named. An
# installation is a branch carrying its own map, clusters/active/<branch>.yaml; the
# ceiling is measured against each map's stage, and an installation the channel does
# not admit is left as it stands and said so. A first machine, whose branch does not
# exist yet, takes the tag as PLATFORM_REF and cuts its branch from it. Every installation
# is put in TARGETS first, in the order origin lists them, because the owner's master
# below is read before anything is pinned.
TARGETS=() # one entry per installation: `pin <fqdn> <stage>` or `leave <fqdn> <stage>`
if [ -n "$FQDN" ]; then
  TARGETS=("pin $FQDN $STAGE")
else
  URL="$(git remote get-url origin)"
  [ -n "$URL" ] || die 'this checkout has no origin to clone, so there is no branch to pin' 69
  for BRANCH in $(git ls-remote --heads origin | sed 's|.*refs/heads/||' | sort); do
    [ "$BRANCH" = 'master' ] && continue
    git cat-file -e "refs/remotes/origin/${BRANCH}:clusters/active/${BRANCH}.yaml" 2>/dev/null || continue
    STAGE="$(git show "refs/remotes/origin/${BRANCH}:clusters/active/${BRANCH}.yaml" | value_in_text stage)"
    case " $ADMITS " in
      *" $STAGE "*) TARGETS+=("pin $BRANCH $STAGE") ;;
      *) TARGETS+=("leave $BRANCH ${STAGE:-unstated}") ;;
    esac
  done
fi
CONFIG_DIR="$(git rev-parse --show-toplevel)/lifecycle"

# NOTHING IS PINNED ON THE OWNER'S MASTER BEFORE ITS RECOVERY FOLDER HOLDS EVERY ARCHIVE OF THE TAG. That
# machine pulls every image from its own zot and fetches its engine from it, so a cold start of it, a first
# installation or a restore, reads them from <fqdn>/recovery/ on the storage box instead (lifecycle/driver.sh)
# and stops at the first archive the folder lacks. The publish run of the tag writes the folder only after it
# has filled the mirror (recovery-export), so a pin that waited for the mirror alone could name a tree whose
# archives never arrived. The owner's master is the installation whose zot is the tree's global.buildRegistry,
# and its archives are those files/recovery-folder.sh of the tree at the tag names for the stage of its map.
# Each must stand in the folder under its name, which the run gives an archive only once it has held it to
# the tree, and rclone only once the upload is whole (it writes to a .partial name until then). The folder is
# listed by a short pod on that master, which the release starts through the operator door of that
# installation's config beside this tree, the door master-backup knocks at. The pod runs the rclone image of
# the tree at the tag with the storage-box login of the Secret recovery-box, the one the publish run writes
# the folder with, so this machine needs no rclone and no value of that login ever reaches it. The wait is the
# one the mirror already spent, and each attempt is bounded by what is left of it.
#
# TWO STATES READ NOTHING. A tree at the tag without files/recovery-folder.sh names no folder, and its driver
# reads none. And the publish run of the tag runs the pipeline of the tree the owner's branch stands on: where
# that tree writes no folder yet, nothing the tag starts writes one, and waiting for it would never pin the
# tag that brings the writer. The release says so and pins, and the release after it reads the folder back.
RECOVERY_LIB='clusters/inventories/consumer-build/files/recovery-folder.sh'
RECOVERY_FQDN=''
RECOVERY_STAGE=''
if [ -f "$LISTED/tree/$RECOVERY_LIB" ]; then
  # shellcheck disable=SC1090
  . "$LISTED/tree/$RECOVERY_LIB"
  RECOVERY_REGISTRY="$(recovery_registry "$LISTED/tree")" \
    || die "the tree at $TAG names no registry its images are pulled from - the line above says why - and nothing was pinned"
  case "$RECOVERY_REGISTRY" in
    zot.*) RECOVERY_FQDN="${RECOVERY_REGISTRY%%/*}"; RECOVERY_FQDN="${RECOVERY_FQDN#zot.}" ;;
  esac
  for ENTRY in ${TARGETS[@]+"${TARGETS[@]}"}; do
    case "$ENTRY" in "pin $RECOVERY_FQDN "*) RECOVERY_STAGE="${ENTRY##* }" ;; esac
  done
fi
branch_carries() { # fqdn, path -> 0 where the tree its install branch stands on carries the path
  if [ -n "$FQDN" ]; then [ -f "$WORK/$2" ]; else git cat-file -e "refs/remotes/origin/$1:$2" 2>/dev/null; fi
}

# THE POD THAT LISTS THE FOLDER, one per attempt. Its image and its login are the define blocks
# consumer-build.rcloneImage, .recoveryBoxEnv and .recoveryBoxLogin of the tree at the tag, which the step present
# of recovery-export runs with, so the digest and the login stand in one place. It carries the label the pinhole
# recovery-export-egress selects, the only way out of the namespace to port 22, and runs as pipeline-sa with no
# token. The namespace is the one this tree's publish run writes the folder from, which holds recovery-box.
# rclone's standard error stays in the pod unless the listing fails; then it leaves with the values of the host
# and the user replaced by the names of their keys, because an sftp line can carry both. So a pod that listed
# the folder logs the listing alone, and no value of the login leaves the cluster.
RECOVERY_NAMESPACE='hostyour-cloud-build'
recovery_define() { # name -> the body of that define block of the tree's consumer-build/templates/_helpers.tpl
  sed -n "/^{{- define \"consumer-build.$1\" -}}\$/,/^{{- end -}}\$/p" \
    "$LISTED/tree/clusters/inventories/consumer-build/templates/_helpers.tpl" | sed '1d;$d'
}
recovery_listing_pod() { # pod name, its bound in seconds -> the manifest
  cat <<POD
apiVersion: v1
kind: Pod
metadata:
  name: $1
  labels:
    tekton.dev/pipelineTask: recovery-export
spec:
  restartPolicy: Never
  serviceAccountName: pipeline-sa
  automountServiceAccountToken: false
  activeDeadlineSeconds: $2
  containers:
    - name: listing
      image: $RECOVERY_IMAGE
      env:
$(printf '%s\n' "$RECOVERY_BOX_ENV" | sed 's/^/        /')
      resources:
        requests: { cpu: 50m, memory: 64Mi }
        limits: { cpu: 500m, memory: 256Mi }
      command:
        - /bin/sh
        - -c
        - |
          set -eu
$(printf '%s\n' "$RECOVERY_BOX_LOGIN" | sed 's/^/          /')
          rclone lsf --recursive --files-only box:$RECOVERY_FQDN/recovery/ > /tmp/listing 2> /tmp/rclone.err || {
            status=\$?
            awk 'function masked(line, value, word,  at, out) {
                   if (value == "") return line
                   while ((at = index(line, value)) > 0) { out = out substr(line, 1, at - 1) word; line = substr(line, at + length(value)) }
                   return out line
                 }
                 { print masked(masked(\$0, ENVIRON["STORAGE_BOX_HOST"], "recovery-box.host"), ENVIRON["STORAGE_BOX_USER"], "recovery-box.user") }' /tmp/rclone.err >&2
            exit "\$status"
          }
          cat /tmp/listing
POD
}
# WHAT THE MASTER RUNS, read by bash -s from the session's standard input, which is why every command but the
# create reads /dev/null. It creates the pod, deletes it on every way out, and reads its phase every 2 seconds
# until the pod has Succeeded or Failed, or 60 seconds past its own bound, in which the cluster ends it. The phase
# decides: the log of a pod that Succeeded is the listing, on the standard output; anything else ends with one
# line on the standard error that names the pod, its phase, the reasons and its last line.
recovery_listing_script() { # pod name, its bound in seconds -> the script
  printf "namespace='%s' pod='%s' bound='%s'\n" "$RECOVERY_NAMESPACE" "$1" "$2"
  cat <<'MASTER'
set -u
pod_api() { microk8s.kubectl -n "$namespace" "$@" < /dev/null; }
microk8s.kubectl -n "$namespace" create -f - >&2 <<'POD' || exit
MASTER
  recovery_listing_pod "$1" "$2"
  cat <<'MASTER'
POD
trap 'pod_api delete pod "$pod" --ignore-not-found > /dev/null' EXIT
trap 'exit 1' HUP INT TERM PIPE
state=''
while :; do
  state="$(pod_api get pod "$pod" -o 'jsonpath={.status.phase} {.status.reason} {.status.containerStatuses[*].state.waiting.reason}{.status.containerStatuses[*].state.terminated.reason}')"
  case "$state" in
    'Succeeded '*) pod_api logs "$pod"; exit ;;
    'Failed '*) break ;;
  esac
  [ "$SECONDS" -lt $((bound + 60)) ] || break
  sleep 2
done
read -r phase reasons <<< "$state"
last="$(pod_api logs "$pod" --tail=1 2>&1 | tail -n 1)"
echo "the pod $pod stands ${phase:-unread}${reasons:+ ($reasons)} after ${SECONDS}s: ${last:-it logged nothing}" >&2
exit 1
MASTER
}
# ONE ATTEMPT is one ssh session, key only, as master-backup opens it, kept alive as release-unit keeps its own.
# The pod's bound is the wait that is left, and at least 120 seconds, which fit a pull of the image and one
# listing, so the last attempt is a real one.
recovery_listing() { # -> the files of the recovery folder, one per line; why not, on the standard error
  local bound=$((MIRROR_DEADLINE - SECONDS))
  [ "$bound" -ge 120 ] || bound=120
  recovery_listing_script "recovery-folder-listing-$(date -u +%Y%m%d%H%M%S)" "$bound" \
    | ssh -p 22 -o BatchMode=yes -o ConnectTimeout=20 -o StrictHostKeyChecking=accept-new \
      -o ServerAliveInterval=15 -o ServerAliveCountMax=4 "$RECOVERY_DOOR" 'bash -s'
}
if [ -n "$RECOVERY_STAGE" ] && ! branch_carries "$RECOVERY_FQDN" "$RECOVERY_LIB"; then
  say "release: the recovery folder of $RECOVERY_FQDN is not read: the publish run of $TAG runs the pipeline of the tree branch $RECOVERY_FQDN stands on, and that tree writes no recovery folder yet. Until a later release reads the folder back, a cold start of $RECOVERY_FQDN from its branch stops at the first archive the folder lacks"
elif [ -n "$RECOVERY_STAGE" ]; then
  RECOVERY_CONFIG="$CONFIG_DIR/config.${RECOVERY_FQDN%%.*}.env"
  [ -r "$RECOVERY_CONFIG" ] \
    || die "there is no config at $RECOVERY_CONFIG, and the operator door of $RECOVERY_FQDN in it is what the release starts the pod that lists its recovery folder through before it pins that installation. Nothing was pinned" 66
  # shellcheck disable=SC1091
  . "$(dirname "$0")/require-owner-only.sh" \
    || die 'require-owner-only.sh is not beside this file. It is the guard every reader of a config puts on it' 66
  require_owner_only "$RECOVERY_CONFIG" \
    || die "$RECOVERY_CONFIG $REACH and carries credentials, the storage-box password among them. Run: $OWNER_ONLY_COMMAND" 77
  RECOVERY_OPERATOR="$(config_value "$RECOVERY_CONFIG" OPERATOR_USER)"
  [ -n "$RECOVERY_OPERATOR" ] \
    || die "$RECOVERY_CONFIG states no OPERATOR_USER, and the operator door of $RECOVERY_FQDN is what the release starts the pod that lists its recovery folder through before it pins that installation. Nothing was pinned" 65
  # The door is MACHINE_HOST where the config states one, and the owner's master where not, as every launcher knocks.
  RECOVERY_MACHINE_HOST="$(config_value "$RECOVERY_CONFIG" MACHINE_HOST)"
  RECOVERY_DOOR="$RECOVERY_OPERATOR@${RECOVERY_MACHINE_HOST:-$RECOVERY_FQDN}"
  RECOVERY_IMAGE="$(recovery_define rcloneImage)"
  RECOVERY_BOX_ENV="$(recovery_define recoveryBoxEnv)"
  RECOVERY_BOX_LOGIN="$(recovery_define recoveryBoxLogin)"
  [ -n "$RECOVERY_IMAGE" ] && [ -n "$RECOVERY_BOX_ENV" ] && [ -n "$RECOVERY_BOX_LOGIN" ] \
    || die "the tree at $TAG states no consumer-build.rcloneImage, .recoveryBoxEnv or .recoveryBoxLogin in clusters/inventories/consumer-build/templates/_helpers.tpl, and the pod that lists the recovery folder of $RECOVERY_FQDN runs with them. Nothing was pinned"
  recovery_archives "$LISTED/tree" "$RECOVERY_STAGE" > "$LISTED/recovery.plan" \
    || die "the tree at $TAG names no archives for the recovery folder of $RECOVERY_FQDN - the line above says why - and nothing was pinned"
  RECOVERY_COUNT="$(grep -c . "$LISTED/recovery.plan")"
  while :; do
    BOX_LISTED=1
    recovery_listing > "$LISTED/recovery.present" 2> "$LISTED/recovery.err" \
      || { BOX_LISTED=''; : > "$LISTED/recovery.present"; }
    UNHELD="$(while read -r path name _; do
      grep -qxF -- "$path" "$LISTED/recovery.present" || printf '%s (%s)\n' "$path" "$name"
    done < "$LISTED/recovery.plan")"
    [ -z "$UNHELD" ] && break
    if [ "$SECONDS" -ge "$MIRROR_DEADLINE" ]; then
      [ -n "$BOX_LISTED" ] \
        || die "the pod that lists box:$RECOVERY_FQDN/recovery/, started on $RECOVERY_FQDN through $RECOVERY_DOOR, listed nothing after ${MIRROR_WAIT}s ($(tail -n 1 "$LISTED/recovery.err" | tr -d '\r')), so none of the $RECOVERY_COUNT archives of $TAG that a cold start of $RECOVERY_FQDN reads there was found. Nothing was pinned. Release again once it does: the tag is reused" 69
      die "the recovery folder of $RECOVERY_FQDN holds $((RECOVERY_COUNT - $(printf '%s\n' "$UNHELD" | grep -c .))) of the $RECOVERY_COUNT archives of $TAG after ${MIRROR_WAIT}s: it lacks $(printf '%s\n' "$UNHELD" | sed 's/$/;/' | tr '\n' ' ')and a cold start of $RECOVERY_FQDN stops at the first of them. The recovery-export of the publish run of $TAG on the owner's master writes them. Nothing was pinned. Read that run, then release again: the tag is reused" 69
    fi
    sleep 30
  done
  say "release: the recovery folder of $RECOVERY_FQDN holds all $RECOVERY_COUNT archives of $TAG"
fi

pin_installation() { # fqdn -> the map on its branch records the tag; PINNED gains the name
  local fqdn="$1" work map held
  work="$(mktemp -d)"
  # THE CLONE IS REMOVED BELOW, straight after the commit and the push, and a commit starts
  # `git maintenance run --auto --detach`, which forks away and takes objects/maintenance.lock in the
  # clone after this function has gone on. `rm -rf` loses that race now and then and ends "Directory not
  # empty" on the standard error. `clone -c` writes the setting into the clone's own config.
  git clone --quiet -c maintenance.auto=false --single-branch --branch "$fqdn" "$URL" "$work" \
    || die "origin has no branch $fqdn. An installation is pinned on its own install branch, and there is none of that name" 66
  map="clusters/active/${fqdn}.yaml"
  [ -f "$work/$map" ] \
    || die "branch $fqdn carries no $map. That map is where an installation records what it is, and the pin is one line in it" 66
  held="$(value_in_file "$work/$map" release)"
  if [ "$held" = "$TAG" ]; then
    say "release: $map already records $TAG, so it is left as it stands"
  else
    write_value_in_file "$work/$map" release "$TAG"
    # THE SUBJECT OPENS WITH `release:` because the push gate excuses a release stamp from naming
    # an issue by that word and by nothing else. The clone carries no hooks, so the gate never judges
    # this commit here — it judges it wherever the same commit is pushed from a checkout that does
    # (simetrixch/hostyour-manager#132).
    git -C "$work" add -- "$map" \
      || die "the pin could not be staged in $map"
    git -C "$work" commit --quiet -m "release: pin $fqdn to $TAG" -m 'Written by the release of the platform tree, once the tag stood on the remote.' \
      || die "the pin of $fqdn to $TAG could not be committed"
    git -C "$work" push --quiet origin "$fqdn" \
      || die "the pin of $fqdn to $TAG could not be pushed, so it is a pin only this machine believes" 74
    say "release: pinned $fqdn to $TAG in $map"
  fi
  rm -rf "$work"
  PINNED+=("$fqdn")
}
PINNED=()
[ -z "$FQDN" ] || rm -rf "$WORK"
